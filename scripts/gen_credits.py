"""Build CREDITS.md's asset section from assets/SOURCES.yaml.

    uv run python scripts/gen_credits.py          # rewrite the section
    uv run python scripts/gen_credits.py --check  # exit 1 if it is out of date

It also writes src/credits_data.py, the credits page's text, which the game imports so it
needs no YAML library at runtime (the browser build has none).

The section sits between the two MARKERS in CREDITS.md; everything outside
them is hand-written. tests/test_sources.py runs the check, so the credits
can't drift from the data.

`own` files are credited to the developer, with the AI tool named when the entry has
`generated_with`. Files whose `source` is `unknown` are not credited to anyone: the
section lists them under "Pending replacement" (only when there are any) with the `todo`
from SOURCES.yaml instead.
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "assets" / "SOURCES.yaml"
CREDITS = ROOT / "CREDITS.md"
CREDITS_DATA = ROOT / "src" / "credits_data.py"
BEGIN = "<!-- assets:begin (generated by scripts/gen_credits.py from assets/SOURCES.yaml) -->"
END = "<!-- assets:end -->"
LICENSE_LINKS = {
    "CC0-1.0": "[CC0 1.0](https://creativecommons.org/publicdomain/zero/1.0/)",
    "OFL-1.1": "[SIL OFL 1.1](https://openfontlicense.org)",
    "CC-BY-3.0": "[CC BY 3.0](https://creativecommons.org/licenses/by/3.0/)",
    "CC-BY-SA-4.0": "[CC BY-SA 4.0](https://creativecommons.org/licenses/by-sa/4.0/)",
}
REPO_SOURCES = (
    "https://github.com/vectorviolet/the-hunted/blob/main/assets/SOURCES.yaml"
)
UNKNOWN = "unknown"


def load_sources(path: Path = SOURCES) -> dict[str, Any]:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    assert isinstance(data, dict)
    return data


def _group_label(rel: str) -> str:
    """The folder a file is listed under: its first two path parts (a folder
    with a trailing slash), or the file itself when it sits directly there."""
    parts = rel.split("/")
    if len(parts) <= 2:
        return f"assets/{rel}"
    return "assets/" + "/".join(parts[:2]) + "/"


def pending_lines(files: dict[str, Any]) -> list[str]:
    """One bullet per (folder, todo) for the files that still have a `todo`:
    an unknown source, or a known one that is being replaced."""
    groups: dict[tuple[str, str, bool], int] = {}
    for rel, entry in sorted(files.items()):
        unknown = entry["source"] == UNKNOWN
        if not unknown and "todo" not in entry:
            continue
        key = (_group_label(rel), entry.get("todo", "origin not confirmed"), unknown)
        groups[key] = groups.get(key, 0) + 1
    return [
        f"- `{label}` ({count} file{'s' if count != 1 else ''}"
        f"{'' if unknown else ', credited above'}): {todo}"
        for (label, todo, unknown), count in groups.items()
    ]


def change_lines(packs: dict[str, Any]) -> list[str]:
    """One bullet per pack whose files were changed (CC BY asks to say so)."""
    return [
        f"- {pack['name']}: {pack['changes']}"
        for _, pack in sorted(packs.items())
        if "changes" in pack
    ]


def attribution_lines(packs: dict[str, Any]) -> list[str]:
    """One bullet per pack whose license asks for a credit line."""
    return [
        f"- {pack['name']} ({LICENSE_LINKS.get(pack['license'], pack['license'])}): "
        f"{pack['attribution']}"
        for _, pack in sorted(packs.items())
        if "attribution" in pack
    ]


def own_credit_lines(files: dict[str, Any]) -> list[str]:
    """One line per (how it was made, folder) for the `own` files. An entry with
    `generated_with` was AI-generated by the developer; the rest were made by hand."""
    groups: dict[tuple[str, str], list[str]] = {}
    for rel, entry in sorted(files.items()):
        if entry["source"] != "own":
            continue
        folder, _, name = rel.rpartition("/")
        groups.setdefault((entry.get("generated_with", ""), folder), []).append(name)
    return [
        (
            f"AI-generated by its developer with {tool} and post-processed"
            if tool
            else "Made for this game by its developer"
        )
        + f": {', '.join(names)} (in assets{'/' + folder if folder else ''})."
        for (tool, folder), names in groups.items()
    ]


def render(data: dict[str, Any]) -> str:
    packs, files = data["packs"], data["files"]
    counts = Counter(entry["source"] for entry in files.values())
    lines = [
        "## Assets",
        "",
        "| Pack | Author | License | Used for | Files |",
        "|---|---|---|---|---|",
    ]
    for slug in sorted(packs, key=lambda s: (-counts[s], s)):
        pack = packs[slug]
        lines.append(
            f"| [{pack['name']}]({pack['url']}) | {pack['author']} "
            f"| {LICENSE_LINKS.get(pack['license'], pack['license'])} "
            f"| {pack['used_for']} | {counts[slug]} |"
        )
    lines += [""]
    for line in own_credit_lines(files):
        lines += [line, ""]
    attributions = attribution_lines(packs)
    if attributions:
        lines += ["### Attribution", "", *attributions, ""]
    changes = change_lines(packs)
    if changes:
        lines += ["### Changes to the original files", "", *changes, ""]
    pending = pending_lines(files)
    if pending:
        lines += [
            "### Pending replacement",
            "",
            "These files are waiting for a source or a replacement. Files marked "
            "credited above are replaced for license reasons while their pack stays "
            f"credited. The other {counts[UNKNOWN]} have no confirmed source or "
            "license: they are not credited to anyone and are not covered by the MIT "
            "license.",
            "",
            *pending,
            "",
        ]
    lines += [
        "CC0 assets need no attribution; they are credited here anyway. The OFL font is",
        "bundled unmodified."
        + (
            " CC BY and CC BY-SA assets require attribution (see above)."
            if attributions
            else ""
        )
        + " Each pack's own license text ships with the game: "
        + ", ".join(f"`licenses/assets/{slug}.txt`" for slug in sorted(packs))
        + ".",
        f"[assets/SOURCES.yaml]({REPO_SOURCES}) in the source repository lists every asset",
        "file with its pack and its original file name there.",
    ]
    return "\n".join(lines)


def updated_credits(text: str, section: str) -> str:
    start, end = text.find(BEGIN), text.find(END)
    if start == -1 or end == -1 or end < start:
        raise ValueError(f"{CREDITS.name}: missing or misplaced assets markers")
    return f"{text[: start + len(BEGIN)]}\n{section}\n{text[end:]}"


# The credits page's sections. A pack lands in one by where its files live: `fonts/` is fonts,
# `images/` is art, and `sounds/` is music when the pack's `used_for` mentions music, sounds
# otherwise. Files with source `own` are credited to the developer; `unknown` ones to no one.
DEVELOPER = "VectorViolet"
ENGINE_LINES = ("pygame-ce (LGPL 2.1)", "pygamine (MIT)")
OWN = "own"


def _license(slug: str) -> str:
    """A license id as shown on the page: "CC0-1.0" -> "CC0 1.0", "OFL-1.1" -> "OFL 1.1"."""
    return slug.replace("-", " ")


def _pack_line(pack: dict[str, Any]) -> str:
    return f"{pack['name']} - {pack['author']} ({_license(pack['license'])})"


def _own_line(entry: dict[str, Any]) -> str:
    tool = entry.get("generated_with")
    return f"AI-generated with {tool}" if tool else f"Made by {DEVELOPER}"


def _section_of(rel: str, pack: dict[str, Any] | None) -> str | None:
    """The credits section a file belongs to (None for a file in an unexpected folder)."""
    folder = rel.split("/", 1)[0]
    if folder == "fonts":
        return "FONTS"
    if folder == "images":
        return "ART"
    if folder == "sounds":
        used_for = pack["used_for"] if pack else ""
        return "MUSIC" if "music" in used_for else "SOUNDS"
    return None


def credit_sections(data: dict[str, Any]) -> list[tuple[str, list[str]]]:
    """The credits as (heading, lines) pairs, from parsed SOURCES.yaml data."""
    packs: dict[str, Any] = data["packs"]
    lines: dict[str, list[str]] = {
        name: [] for name in ("MUSIC", "SOUNDS", "ART", "FONTS")
    }
    for rel, entry in sorted(data["files"].items()):
        source = entry["source"]
        if source == UNKNOWN:
            continue
        pack = None if source == OWN else packs[source]
        section = _section_of(rel, pack)
        line = _own_line(entry) if pack is None else _pack_line(pack)
        if section is not None and line not in lines[section]:
            lines[section].append(line)
    sections: list[tuple[str, list[str]]] = [("GAME", [DEVELOPER])]
    sections += [(name, found) for name, found in lines.items() if found]
    sections.append(("ENGINE", list(ENGINE_LINES)))
    return sections


def credits_data_module(data: dict[str, Any]) -> str:
    """The text of src/credits_data.py, in the layout `ruff format` keeps as it is."""
    lines = [
        '"""The text of the credits page. Generated by scripts/gen_credits.py from',
        'assets/SOURCES.yaml (so the game needs no YAML library); do not edit by hand."""',
        "",
        "SECTIONS: list[tuple[str, list[str]]] = [",
    ]
    for heading, rows in credit_sections(data):
        lines += ["    (", f"        {json.dumps(heading)},", "        ["]
        lines += [f"            {json.dumps(row, ensure_ascii=False)}," for row in rows]
        lines += ["        ],", "    ),"]
    lines.append("]")
    return "\n".join(lines) + "\n"


def main() -> int:
    data = load_sources()
    text = CREDITS.read_text(encoding="utf-8")
    new = updated_credits(text, render(data))
    module = credits_data_module(data)
    current = CREDITS_DATA.read_text(encoding="utf-8") if CREDITS_DATA.exists() else ""
    if "--check" in sys.argv:
        if new != text or module != current.replace("\r\n", "\n"):
            print(
                "CREDITS.md or src/credits_data.py is out of date: "
                "run scripts/gen_credits.py"
            )
            return 1
        return 0
    CREDITS.write_text(new, encoding="utf-8")
    CREDITS_DATA.write_text(module, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
